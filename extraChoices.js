let extraChoicesApplied = false;

function applyExtraChoices() {
  if (extraChoicesApplied) return;      // safety: never add them twice
  extraChoicesApplied = true;

  Object.keys(extraChoices).forEach(function (storyId) {
    const story = storiesData[storyId];
    if (!story) return;

    extraChoices[storyId].forEach(function (list, epIndex) {
      const ep = story.episodes[epIndex];
      if (!ep) return;

      // The character who reacts to the original wrong choice also
      // reacts to the extra choices (same speaker + avatar).
      const wrongBase = ep.choices.find(function (c) { return !c.correct; }) || ep.choices[0];

      list.forEach(function (extra) {
        ep.choices.push({
          text: extra.text,
          correct: false,
          funny: extra.funny === true,
          skills: { technical: 0, communication: 0, problemSolving: 0, leadership: 0 },
          reaction: { speaker: wrongBase.reaction.speaker, avatar: wrongBase.reaction.avatar, text: extra.reaction }
        });
      });
    });
  });

  // Translations (only the doctor story has them)
  if (typeof storyTranslations !== "undefined") {
    Object.keys(extraTranslations).forEach(function (storyId) {
      const tr = storyTranslations[storyId];
      if (!tr) return;
      extraTranslations[storyId].forEach(function (list, epIndex) {
        const epTr = tr.episodes[epIndex];
        if (!epTr) return;
        list.forEach(function (c) { epTr.choices.push(c); });
      });
    });
  }
}

applyExtraChoices();
