// ===============================================
// extraChoices.js
//
// WHY THIS FILE EXISTS
// Every episode in storyData.js has 2 choices (the right one and
// one wrong one). This file adds TWO MORE choices to every
// episode, so each decision now has 4 options:
//   1. the original right choice          (from storyData.js)
//   2. the original wrong choice          (from storyData.js)
//   3. an extra tempting-but-wrong choice (added here)
//   4. a FUNNY choice, marked funny: true (added here)
//
// HOW IT WORKS
// - extraChoices[storyId][episodeNumber - 1] is a list of the two
//   extra choices for that episode: [ wrong, funny ].
// - applyExtraChoices() (at the bottom) pushes them into
//   storiesData, so story.html does not need to know about them.
// - The extra choices are always wrong (correct: false) and give 0
//   skill points. Their reaction is spoken by the same character
//   who reacts to the original wrong choice.
// - story.html shuffles the order of the buttons every time an
//   episode is shown, so the right answer can be in any position.
// - extraTranslations adds Hindi/English text for the one story
//   that has translations (doctor). Other stories fall back to the
//   original text, like the rest of the app does.
// ===============================================

